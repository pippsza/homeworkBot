/**
 * Скільки ДНІВ лишилось до дати.
 *
 * Рахуємо різницю календарних днів, а не годин. Дедлайни в базі стоять з
 * різним часом доби (23:59, 20:59, 12:35), і різниця в мілісекундах давала
 * для двох робіт на одну дату різні числа - 11 і 12, а до завтрашнього дня
 * писало «через 2 дн.».
 *
 * Округлення саме `round`: у добу переходу на зимовий час 23 або 25 годин,
 * і ділення дало б 0.96 чи 1.04 замість рівної одиниці.
 */
export function daysUntil(target: Date, now: Date = new Date()): number {
  const a = new Date(now);
  a.setHours(0, 0, 0, 0);
  const b = new Date(target);
  b.setHours(0, 0, 0, 0);
  return Math.round((b.getTime() - a.getTime()) / 86_400_000);
}

/** «сьогодні» / «завтра» / «через N дн.» - однаково в усіх повідомленнях бота. */
export function humanDays(days: number): string {
  if (days < 0) return "прострочено";
  if (days === 0) return "сьогодні";
  if (days === 1) return "завтра";
  return `через ${days} дн.`;
}
